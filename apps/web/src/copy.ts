/**
 * Plain sentence for an api error. Traefik replaces the body of 404/500/502/503/504 with HTML, so with no usable code
 * the status decides. `detail` is the `code` of a builder_failed body.
 */
export function errorCopy(code: string | undefined, status?: number, detail?: string): string {
  if (code === 'builder_failed') {
    if (detail === 'unreadable') return E.builderUnreadable;
    if (detail === 'budget') return E.builderBudget;
    if (detail === 'aborted') return E.aborted;
    return E.builderFailed;
  }
  if (code && Object.hasOwn(BY_CODE, code)) return BY_CODE[code]!;
  if (status === 404) return E.status404;
  if (status === 429) return E.status429;
  if (status !== undefined && status >= 500) return E.status5xx;
  return E.generic;
}
